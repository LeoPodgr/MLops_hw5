#!/usr/bin/env python3
"""Publish a new demo model artifact and atomically switch latest.txt.

The command intentionally does not depend on Docker or third-party Python
packages. Connect an existing retraining pipeline to the same file contract:
write <version>.json first, then atomically replace latest.txt.
"""
from __future__ import annotations

import argparse
import json
import os
from datetime import datetime, timezone
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models-dir", type=Path, default=Path(__file__).resolve().parents[1] / "model_registry")
    parser.add_argument("--bias", type=float, default=3.0, help="New model bias; use 3.0 to trigger the high-fraud demo alert")
    parser.add_argument("--threshold", type=float, default=None, help="Optional fraud threshold in (0,1)")
    parser.add_argument("--version", default=None, help="Explicit version; autogenerated if omitted")
    args = parser.parse_args()

    if args.threshold is not None and not 0.0 < args.threshold < 1.0:
        parser.error("--threshold must be between 0 and 1")

    args.models_dir.mkdir(parents=True, exist_ok=True)
    pointer = args.models_dir / "latest.txt"
    current = None
    if pointer.exists():
        current_version = pointer.read_text(encoding="utf-8").strip()
        current_path = args.models_dir / f"{current_version}.json"
        if current_path.exists():
            current = json.loads(current_path.read_text(encoding="utf-8"))

    baseline_path = args.models_dir / "baseline-v1.json"
    if current is None and baseline_path.exists():
        current = json.loads(baseline_path.read_text(encoding="utf-8"))
    if current is None:
        raise SystemExit(f"No existing model artifact found in {args.models_dir}")

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    version = args.version or f"model-{timestamp}"
    if "/" in version or ".." in version or not version:
        parser.error("--version must be a simple file-name component")

    model = {
        "version": version,
        "bias": args.bias,
        "weights": current.get("weights", {}),
        "fraud_threshold": args.threshold if args.threshold is not None else current.get("fraud_threshold", 0.65),
    }
    artifact_path = args.models_dir / f"{version}.json"
    temp_artifact = args.models_dir / f".{version}.json.tmp"
    temp_pointer = args.models_dir / ".latest.txt.tmp"
    temp_artifact.write_text(json.dumps(model, indent=2) + "\n", encoding="utf-8")
    os.replace(temp_artifact, artifact_path)
    temp_pointer.write_text(version + "\n", encoding="utf-8")
    os.replace(temp_pointer, pointer)
    print(f"Published {artifact_path}")
    print(f"latest.txt -> {version}")
    print("The running scorer should hot-load it on the next transaction (no container restart).")


if __name__ == "__main__":
    main()
